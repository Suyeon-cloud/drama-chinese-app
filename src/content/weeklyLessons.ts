// - 영상은 비워 두었다. 교수자가 ‘강의자료 만들기’에서 YouTube 주소를 넣고 원문 시간을 맞추면
//   1주차처럼 영상 위에 자막·표현 카드가 나타난다. 영상이 없을 때 학습자는 대본·표현·퀴즈로 학습한다.
// - 1~8주차는 중국어 → 한국어(중국 드라마), 9~15주차는 한국어 → 중국어(한국 드라마)이다.

import { defaultDirectionForWeek } from "./course";
import type { DraftLens, DraftNote, DraftQuiz, Lesson } from "./types";

const SEED_TIME = "2026-10-22T00:00:00.000Z";

type Note = [source: string, note: string, pinyin: string];
type Quiz = [question: string, options: string[], answer: number, explanation: string];

type WeekSpec = {
  week: number;
  title: string;
  description: string;
  level: "beginner" | "intermediate" | "advanced";
  drama: string;
  /** 원문 대사 (1~8주차 중국어, 9~15주차 한국어) — 한 줄 = 한 문장 */
  lines: string[];
  expressions: Note[];
  grammar: Note[];
  lens: { title: string; source: string; text: string };
  quiz: Quiz[];
};

const note = (week: number, kind: string, i: number, [source, text, pinyin]: Note): DraftNote => ({
  id: `w${week}-${kind}${i + 1}`,
  source,
  note: text,
  pinyin,
  at: null,
});

const buildLesson = (w: WeekSpec): Lesson => {
  const direction = defaultDirectionForWeek(w.week);
  const lens: DraftLens = { id: `w${w.week}-lens1`, ...w.lens, at: null };
  const quiz: DraftQuiz[] = w.quiz.map(([question, options, answer, explanation], i) => ({
    id: `w${w.week}-quiz${i + 1}`,
    question,
    options,
    answer,
    explanation,
  }));
  return {
    id: `lesson-week${String(w.week).padStart(2, "0")}`,
    week: w.week,
    title: w.title,
    description: w.description,
    direction,
    level: w.level,
    status: "published",
    video: { youtubeUrl: "", youtubeId: "", startTime: 0, endTime: 0 },
    source: { dramaTitle: w.drama, episode: "상황 재구성 대사" },
    script: {
      source: "text",
      cues: [],
      updatedAt: SEED_TIME,
      plain: {
        lang: direction === "zh-ko" ? "zh" : "ko",
        lines: w.lines.map((text) => ({ text, start: null })),
        updatedAt: SEED_TIME,
      },
    },
    draft: {
      expressions: w.expressions.map((n, i) => note(w.week, "exp", i, n)),
      grammar: w.grammar.map((n, i) => note(w.week, "gram", i, n)),
      lenses: [lens],
      quiz,
      createdAt: SEED_TIME,
      updatedAt: SEED_TIME,
    },
    createdAt: SEED_TIME,
    updatedAt: SEED_TIME,
  };
};

