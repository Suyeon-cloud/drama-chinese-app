import { defaultDirectionForWeek } from "./course";
import { LEGACY_COURSE_ID } from "./courses";
import type { DraftLens, DraftNote, DraftQuiz, Lesson } from "./types";

const SEED_TIME = "2026-10-26T00:00:00.000Z";

/** [원문 표현, 설명] — 1~8주차는 중국어 표현 + 한국어 설명, 9~15주차는 한국어 표현 + 중국어 표현·설명 */
type Note = [source: string, note: string];
/** 보기의 첫 번째가 정답 (주차마다 정답 위치를 돌려서 넣는다) */
type Quiz = [question: string, options: string[], explanation: string];

type WeekSpec = {
  week: number;
  title: string;
  drama: string;
  /** 장면 설명 */
  scene: string;
  /** 학습 주제 */
  theme: string;
  youtubeId: string;
  /** levels.ts의 HSK 등급 id (hsk1~hsk6) */
  level: string;
  expressions: Note[];
  grammar: Note[];
  lens: { title: string; source: string; text: string };
  quiz: Quiz[];
};

const note = (week: number, kind: string, i: number, [source, text]: Note): DraftNote => ({
  id: `w${week}-${kind}${i + 1}`,
  source,
  note: text,
  at: null,
});

const buildLesson = (w: WeekSpec): Lesson => {
  const direction = defaultDirectionForWeek(w.week);
  const lens: DraftLens = { id: `w${w.week}-lens1`, ...w.lens, at: null };
  const quiz: DraftQuiz[] = w.quiz.map(([question, options, explanation], i) => {
    // 정답(첫 보기)을 주차·문항마다 다른 자리로 옮긴다.
    const shift = (w.week + i) % options.length;
    const rotated = [...options.slice(options.length - shift), ...options.slice(0, options.length - shift)];
    return { id: `w${w.week}-quiz${i + 1}`, question, options: rotated, answer: shift, explanation };
  });
  return {
    id: `lesson-week${String(w.week).padStart(2, "0")}`,
    // 3과목 개편 전 15주 계획이라 ‘기존 자료’로 보관한다. (새 과목 주차와 영상이 같은 것만 나중에 옮긴다)
    courseId: LEGACY_COURSE_ID,
    week: w.week,
    title: w.title,
    description: `${w.scene} · 학습 주제: ${w.theme}`,
    direction,
    level: w.level,
    // 대본(자막)을 채우고 표현을 실제 대사에 맞게 고친 뒤 공개한다.
    status: "draft",
    // 클립 전체가 학습 구간 (endTime 0 = 영상 끝까지)
    video: { youtubeUrl: `https://youtu.be/${w.youtubeId}`, youtubeId: w.youtubeId, startTime: 0, endTime: 0 },
    source: { dramaTitle: w.drama, episode: "학습 클립" },
    script: { source: "text", cues: [], updatedAt: null },
    draft: {
      expressions: w.expressions.map((n, i) => note(w.week, "exp", i, n)),
      grammar: w.grammar.map((n, i) => note(w.week, "gram", i, n)),
      lenses: [lens],
      quiz,
      createdAt: SEED_TIME,
      updatedAt: SEED_TIME,
    },
    createdAt: SEED_TIME,
    updatedAt: SEED_TIME,
  };
};

